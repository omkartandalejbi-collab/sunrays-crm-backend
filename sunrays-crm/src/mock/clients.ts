const today = new Date();

const generateHistory = (status: string, notes?: string, createdAt?: string): Interaction[] => {
  const history: Interaction[] = [];
  
  if (notes) {
    history.push({
      id: `int-${Math.random().toString(36).substr(2, 9)}`,
      employee: 'Jane Doe',
      action: 'Status Updated',
      status: status,
      remark: notes,
      createdAt: subHours(today, Math.floor(Math.random() * 5)).toISOString()
    });
  } else if (status !== 'New') {
    history.push({
      id: `int-${Math.random().toString(36).substr(2, 9)}`,
      employee: 'Jane Doe',
      action: 'Status Updated',
      status: status,
      remark: `Status changed to ${status}`,
      createdAt: subHours(today, 2).toISOString()
    });
  }

  history.push({
    id: `int-${Math.random().toString(36).substr(2, 9)}`,
    employee: 'System',
    action: 'Lead Assigned',
    status: 'New',
    remark: 'Lead assigned to Jane Doe.',
    createdAt: createdAt || subDays(today, 5).toISOString()
  });

  return history;
};

